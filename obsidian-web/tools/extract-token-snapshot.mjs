#!/usr/bin/env node
// extract-token-snapshot — dsw token 快照导出工具（ARC-5：分享页 token 快照导出）
//
// 用途：从宿主 dsw 主题源（dsh-client-ui-theme）抽出本包消费的 --dsw-*/--ds-* token 的
// **具体取值**（light=body / dark=body[data-ds-dark-theme]，var() 链递归解析到字面值），
// 生成 lib/share-theme.js 的快照块（// SNAPSHOT-BEGIN … // SNAPSHOT-END）。
// 分享页无宿主变量环境，靠这份快照内联自洽（样式独立可离线——test/share-theme.test.mjs 锁形）。
//
// 用法：
//   node tools/extract-token-snapshot.mjs            # 打印快照块
//   node tools/extract-token-snapshot.mjs --write    # 回写 lib/share-theme.js 快照块
//   node tools/extract-token-snapshot.mjs --theme <path>  # 指定主题源（默认见 DEFAULT_THEME）
//
// 快照名集 = 消费面（web/src/styles.css + lib/share-theme.js 规则区）自动收集；
// 主题源变更（dsh 升版改色板）后重跑本工具即可刷新快照。
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const PKG = path.dirname(HERE)
const DEFAULT_THEME = '/usr/local/lib/node_modules/@deepseek-ai/dsh/node_modules/@deepseek-ai/dsh-client-ui-theme/lib/client.js'
const SHARE_THEME_JS = path.join(PKG, 'lib/share-theme.js')
const BEGIN = '// SNAPSHOT-BEGIN: generated by tools/extract-token-snapshot.mjs'
const END = '// SNAPSHOT-END: generated by tools/extract-token-snapshot.mjs'

const argv = process.argv.slice(2)
const argOf = (flag) => (argv.includes(flag) ? argv[argv.indexOf(flag) + 1] : null)
const themePath = argOf('--theme') ?? process.env.DSW_THEME_PATH ?? DEFAULT_THEME

/** JS 源里的 CSS 字符串常量抽取（剥 \" 转义；只取含 { 的=样式体） */
function cssStrings(jsSrc) {
  const out = []
  let cur = null
  for (let i = 0; i < jsSrc.length; i += 1) {
    const c = jsSrc[i]
    if (cur === null) {
      if (c === '"') cur = []
      continue
    }
    if (c === '\\') {
      cur.push(jsSrc[i + 1])
      i += 1
      continue
    }
    if (c === '"') {
      const text = cur.join('')
      if (text.includes('{')) out.push(text)
      cur = null
      continue
    }
    cur.push(c)
  }
  return out.join('\n')
}

/** 顶层规则解析（sel → body）；@media 等嵌套块递归进内层收集 */
function parseRules(cssText, into = []) {
  let i = 0
  let anchor = 0
  while (i < cssText.length) {
    if (cssText[i] === '{') {
      const sel = cssText.slice(anchor, i).trim()
      let depth = 1
      let j = i + 1
      while (j < cssText.length && depth > 0) {
        if (cssText[j] === '{') depth += 1
        else if (cssText[j] === '}') depth -= 1
        j += 1
      }
      const body = cssText.slice(i + 1, j - 1)
      if (sel.startsWith('@')) parseRules(body, into)
      else into.push([sel, body])
      i = j
      anchor = j
      continue
    }
    i += 1
  }
  return into
}

function collectDefs(cssText) {
  // 按 selector 分桶（同 selector 同名冲突=源文件真冲突必炸；不同 selector=特异性覆盖，
  // 文档序后者覆盖，darwin 等平台覆写不误报）。
  const bySel = new Map()
  for (const [sel, body] of parseRules(cssText)) {
    const map = bySel.get(sel) ?? new Map()
    for (const m of body.matchAll(/(--d[a-z0-9-]+)\s*:\s*([^;}]+)/g)) {
      const prev = map.get(m[1])
      if (prev !== undefined && prev !== m[2].trim()) {
        throw new Error(`同 selector 同名 token 冲突（${sel} → ${m[1]}）：${prev} | ${m[2]}`)
      }
      map.set(m[1], m[2].trim())
    }
    bySel.set(sel, map)
  }
  const light = {}
  const dark = {}
  const base = {}
  const merge = (sel, map) => Object.assign(sel === 'dark' ? dark : sel === 'light' ? light : base, Object.fromEntries(map))
  for (const [sel, map] of bySel) {
    const isDark = sel.includes('[data-ds-dark-theme]')
    const isBody = /(^|\s)body$/.test(sel)
    merge(isDark ? 'dark' : isBody ? 'light' : 'base', map)
  }
  return { light, dark, base }
}

/** var() 链递归解析（主题桶 → light 继承（CSS 语义：body 定义暗色同样继承）→ :root 兜底） */
function resolveValue(maps, value, depth = 0, seen = new Set()) {
  if (depth > 8) throw new Error(`var() 链过深：${value}`)
  return String(value).replace(/var\((--d[a-z0-9-]+)\)/g, (whole, name) => {
    if (seen.has(name)) throw new Error(`var() 自环：${name}`)
    const next = maps.map((m) => m[name]).find((v) => v !== undefined)
    if (next === undefined) throw new Error(`主题源缺 ${name}（快照无法闭合）`)
    const sub = new Set(seen)
    sub.add(name)
    return resolveValue(maps, next, depth + 1, sub)
  })
}

function consumerNames() {
  const names = new Set()
  const files = [path.join(PKG, 'web/src/styles.css')]
  if (fs.existsSync(SHARE_THEME_JS)) files.push(SHARE_THEME_JS)
  for (const f of files) {
    const raw = fs.readFileSync(f, 'utf8')
    for (const m of raw.matchAll(/var\((--ds[w]?-[a-z0-9-]+)/g)) names.add(m[1])
  }
  return [...names].sort()
}

function buildSnapshotBlock() {
  const jsSrc = fs.readFileSync(themePath, 'utf8')
  const { light, dark, base } = collectDefs(cssStrings(jsSrc))
  const names = consumerNames()
  if (names.length === 0) throw new Error('消费面零 token（先写 styles.css / share-theme.js 规则）')
  const fmt = (map, tag, maps) => {
    const rows = names.map((n) => {
      const raw = maps.map((m) => m[n]).find((v) => v !== undefined)
      if (raw === undefined) throw new Error(`${tag} 缺 ${n}`)
      return `    ${JSON.stringify(n)}: ${JSON.stringify(resolveValue(maps, raw))}`
    })
    return `  ${tag}: {\n${rows.join(',\n')},\n  }`
  }
  return [fmt(light, 'light', [light, base]), fmt(dark, 'dark', [dark, light, base])].join(',\n')
}

const block = buildSnapshotBlock()
if (argv.includes('--write')) {
  const src = fs.readFileSync(SHARE_THEME_JS, 'utf8')
  const b = src.indexOf(BEGIN)
  const e = src.indexOf(END)
  if (b < 0 || e < 0 || e < b) throw new Error('share-theme.js 缺 SNAPSHOT-BEGIN/END 标记')
  const next = src.slice(0, b + BEGIN.length) + `\n${block}\n  ` + src.slice(e)
  fs.writeFileSync(SHARE_THEME_JS, next)
  console.log(`快照块已回写：${path.relative(PKG, SHARE_THEME_JS)}（${consumerNames().length} token）`)
} else {
  console.log(block)
}
